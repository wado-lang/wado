#!/usr/bin/env python3
# Generates branch_hint_big.wado: a hot loop with N independent rarely-taken
# `unlikely` branches, each with a sizeable inline cold body. Without hoisting,
# the hot path is fragmented across the cold bodies. Used to probe whether
# i-cache/fetch pressure makes the branch-hint layout effect measurable.
N = 16
lines = []
lines.append("// GENERATED by gen_big.py — do not edit by hand.")
lines.append("// I-cache/fetch-pressure branch-hint benchmark.")
lines.append('use { println, Stdout } from "core:cli";')
lines.append("")
lines.append("fn workload(iters: i64, seed: i64) -> i64 {")
lines.append("    let mut x: i64 = seed;")
lines.append("    let mut acc: i64 = 0;")
lines.append("    let mut i: i64 = 0;")
lines.append("    while i < iters {")
for k in range(N):
    c1 = 2654435761 + k * 1000003
    c2 = 40503 + k * 7919
    c3 = 7 + k
    s1 = 5 + (k % 17)
    s2 = 11 + (k % 13)
    s3 = 3 + (k % 19)
    s4 = 7 + (k % 23)
    lines += [
        "        x = x ^ (x << 13);",
        "        x = x ^ (x >> 7);",
        "        x = x ^ (x << 17);",
        "        acc = acc + (x & 7);",
        f"        if builtin::unlikely((x & 1023) == {k}) {{",
        f"            acc = acc + x * {c1};",
        f"            acc = acc ^ (acc << {s1});",
        f"            acc = acc + (x >> {s3}) * {c2};",
        f"            acc = acc ^ (acc >> {s2});",
        f"            acc = acc + (x & 65535) * {c3};",
        f"            acc = acc ^ (acc << {s4});",
        f"            acc = acc + x * {c1 + 17};",
        f"            acc = acc ^ (acc >> {s1});",
        "        }",
    ]
lines.append("        i = i + 1;")
lines.append("    }")
lines.append("    return acc;")
lines.append("}")
lines.append("")
lines.append("export fn run() with Stdout {")
lines.append("    let r = workload(60000000, 88172645463325252);")
lines.append("    println(`{r}`);")
lines.append("}")
import os
out = os.path.join(os.path.dirname(__file__), "branch_hint_big.wado")
open(out, "w").write("\n".join(lines) + "\n")
print("wrote", out, N, "branches")
