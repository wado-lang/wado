// Writes tests/generated/oracle_test.wado: for each case in
// tests/oracle/cases.json, what Node's RegExp finds in each input, with the
// `u` flag, as Re reports it. Node is a black-box oracle: Re iterates matches
// by its own rule, so this script runs that loop and asks Node only for the
// leftmost match from each position. Node runs only here; the expectations are
// committed, so CI needs none.
//
// Run from the repository root: mise run oracle-re

import { readFileSync, writeFileSync } from "node:fs";
import { wadoLiteral as literal, wadoPattern } from "./wado-literal.mjs";

const root = new URL("..", import.meta.url);
const cases = JSON.parse(readFileSync(new URL("tests/oracle/cases.json", root), "utf8"));

const bytes = (text, index) => Buffer.byteLength(text.slice(0, index));

// Each match `find_iter` reports, its groups as byte spans; `-` for a group
// that took no part.
function spans(pattern, text) {
  const regex = new RegExp(pattern, "dgu");
  const found = [];
  let next = 0;
  let lastEnd = -1;
  while (next <= text.length) {
    regex.lastIndex = next;
    const m = regex.exec(text);
    if (m === null) {
      break;
    }
    const start = m.index;
    const end = start + m[0].length;
    if (end > start) {
      next = end;
    } else if (end < text.length) {
      next = end + (text.codePointAt(end) > 0xffff ? 2 : 1);
    } else {
      next = end + 1;
    }
    if (start === end && start === lastEnd) {
      continue;
    }
    lastEnd = end;
    found.push(m.indices.map((span) => (span ? `${bytes(text, span[0])}..${bytes(text, span[1])}` : "-")).join(","));
  }
  return found.join(" ");
}

const lines = [
  "// Generated by package-re/scripts/oracle.mjs from tests/oracle/cases.json:",
  "// what Node's RegExp finds with the `u` flag. Regenerate with",
  "// `mise run oracle-re`; do not edit.",
  "",
  'use { Regex } from "../../src/lib.wado";',
  "",
  "fn spans(pattern: String, text: String) -> String {",
  "    let regex = Regex::new(pattern).unwrap();",
  "    let mut found: List<String> = [];",
  "    for let caps of regex.captures_iter(text) {",
  "        let mut groups: List<String> = [];",
  "        for let i of 0..<caps.len() {",
  "            groups.push(match caps[i] {",
  "                Some(m) => `${m.start()}..${m.end()}`,",
  '                None => "-",',
  "            });",
  "        }",
  '        found.push(groups.join(","));',
  "    }",
  '    return found.join(" ");',
  "}",
];
for (const [pattern, texts] of cases) {
  lines.push("", `test ${literal(pattern)} {`);
  for (const text of texts) {
    lines.push(`    assert spans(${wadoPattern(pattern)}, ${literal(text)}) == ${literal(spans(pattern, text))};`);
  }
  lines.push("}");
}
writeFileSync(new URL("tests/generated/oracle_test.wado", root), `${lines.join("\n")}\n`);
