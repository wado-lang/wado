// Writes tests/generated/test262_test.wado: each pattern test262 says the
// grammar rejects, as a parse-phase SyntaxError, and that Node's RegExp
// rejects with the `u` flag too, held to Re's rejecting it. test262 is read as
// data: the literal a test evaluates, and the metadata that says it must fail.
// Node only confirms that the `u` grammar is the one rejecting it, since a
// test without the flag may fail for want of Annex B instead. A property
// `core:icu` knows is held to Re's accepting it instead.
//
// Run from the repository root, with vendor/test262 checked out:
// mise run test262-re

import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const corpus = join(root, "../vendor/test262");
const dirs = ["test/language/literals/regexp", "test/built-ins/RegExp/property-escapes"];

function* files(dir) {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    // The generated property tests list each property's code points: a
    // Unicode version's data, which `core:icu` answers for Re.
    if (statSync(path).isDirectory()) {
      if (name !== "generated") {
        yield* files(path);
      }
    } else if (name.endsWith(".js")) {
      yield path;
    }
  }
}

// The literal a negative test evaluates: the last line after
// `$DONOTEVALUATE();`, when it is one regular expression literal.
function literal(source) {
  const body = source.split("$DONOTEVALUATE();")[1];
  if (body === undefined) {
    return null;
  }
  const lines = body.split("\n").filter((line) => line.trim() !== "");
  if (lines.length !== 1) {
    return null;
  }
  const m = /^\/(.+)\/([dgimsuy]*);?$/.exec(lines[0].trim());
  return m === null ? null : m[1];
}

// The tests naming a property ECMA-262's tables leave out and `core:icu`
// knows. Re takes `\p` from `core:icu`, so it accepts these where test262
// requires a rejection. `\p{Line_Break}` names no value, so it stays an error;
// its negated test names one.
const icuProperties = [
  "unsupported-binary-property-Full_Composition_Exclusion",
  "unsupported-binary-property-Grapheme_Link",
  "unsupported-binary-property-Hyphen",
  "unsupported-binary-property-Prepended_Concatenation_Mark",
  "unsupported-property-Line_Break-with-value",
].flatMap((stem) => [`${stem}.js`, `${stem}-negated.js`]).concat(["unsupported-property-Line_Break-negated.js"]);

function knownToIcu(path) {
  return icuProperties.includes(path.split("/").pop());
}

function rejectsUnderU(pattern) {
  try {
    new RegExp(pattern, "u");
    return false;
  } catch {
    return true;
  }
}

function wado(text) {
  let out = '"';
  for (const c of text) {
    const code = c.codePointAt(0);
    if (c === '"' || c === "\\") {
      out += `\\${c}`;
    } else if (code >= 0x20 && code < 0x7f) {
      out += c;
    } else {
      out += `\\u{${code.toString(16).toUpperCase()}}`;
    }
  }
  return `${out}"`;
}

const lines = [
  "// Generated by package-re/scripts/test262.mjs from vendor/test262: the",
  "// patterns its parse-phase negative tests hold to a SyntaxError, which Node's",
  "// RegExp rejects with the `u` flag too. Regenerate with `mise run test262-re`;",
  "// do not edit.",
  "",
  'use { Regex } from "../../src/lib.wado";',
];
for (const dir of dirs) {
  for (const path of files(join(corpus, dir))) {
    const source = readFileSync(path, "utf8");
    if (!/negative:\s*\n\s*phase: parse\s*\n\s*type: SyntaxError/.test(source)) {
      continue;
    }
    const pattern = literal(source);
    if (pattern === null || !rejectsUnderU(pattern)) {
      continue;
    }
    const name = relative(corpus, path);
    if (knownToIcu(name)) {
      lines.push("", `// core:icu knows the property, so Re accepts it.`, `test ${wado(name)} {`, `    assert Regex::new(${wado(pattern)}).is_ok();`, "}");
    } else {
      lines.push("", `test ${wado(name)} {`, `    assert Regex::new(${wado(pattern)}).is_err();`, "}");
    }
  }
}
writeFileSync(join(root, "tests/generated/test262_test.wado"), `${lines.join("\n")}\n`);
