/// A UCD long name as a Wado case: each `_`-separated word split again at its
/// case humps (`ExtendNumLet`, `ZWSpace`), then capitalized and joined
/// (`ExtendNumLet`, `ZwSpace`).
fn case_name(long: &str) -> String {
    let mut words = Vec::new();
    for word in long.split('_') {
        let chars: Vec<char> = word.chars().collect();
        let mut current = String::new();
        for (i, &c) in chars.iter().enumerate() {
            let hump = i > 0
                && c.is_ascii_uppercase()
                && (chars[i - 1].is_ascii_lowercase()
                    || chars.get(i + 1).is_some_and(|n| n.is_ascii_lowercase()));
            if hump && !current.is_empty() {
                words.push(std::mem::take(&mut current));
            }
            current.push(c.to_ascii_lowercase());
        }
        words.push(current);
    }
    assert!(
        words
            .iter()
            .all(|w| w.starts_with(|c: char| c.is_ascii_lowercase())),
        "`{long}` makes the words {words:?}, which must each start with a letter"
    );
    words.join("-").to_upper_camel_case()
}

/// The property's name in the WIT: `script`, `general-category-group`.
fn wit_name(property: &Property) -> String {
    property.rust_type.to_kebab_case()
}

fn snake_name(property: &Property) -> String {
    wit_name(property).replace('-', "_")
}

fn wit(properties: &[Property]) -> String {
    let mut out = String::new();
    writeln!(out, "// {HEADER}").unwrap();
    out.push_str(
        "
// Each property has exports of its own, so a program carries the data of the
// properties it names and no others. A value crosses as its position in the
// list `core:icu` and this component both generate from ICU4X; a position past
// the end traps.
//
// A name parses through `parse-<property>`, which returns `none` for a name it
// does not answer, never an approximation: a caller complementing an
// approximate set admits real members of the property rather than missing some.
interface properties {
  /// How `parse-<property>` matches a name: exactly as the UCD spells one of
  /// its aliases, or loosely, as UAX #44 matches (case, `_`, `-` and spaces not
  /// significant).
  enum matching {
    strict,
    loose,
  }
",
    );
    for property in properties {
        let name = wit_name(property);
        writeln!(
            out,
            "\n  {name}-ranges: func(value: u16) -> list<tuple<u32, u32>>;"
        )
        .unwrap();
        writeln!(
            out,
            "  {name}-contains: func(value: u16, ch: char) -> bool;"
        )
        .unwrap();
        writeln!(
            out,
            "  parse-{name}: func(name: string, matching: matching) -> option<u16>;"
        )
        .unwrap();
    }
    out.push_str("}\n");
    out
}

fn rust(properties: &[Property]) -> String {
    let mut out = String::new();
    writeln!(out, "// {HEADER}").unwrap();
    out.push_str(
        "
use alloc::string::String;
use alloc::vec::Vec;

use icu::properties::props::*;

use super::exports::wado::icu::properties as wit;
use super::{
    Component, at, binary_contains, binary_ranges, category_contains, category_ranges,
    enumerated_contains, enumerated_ranges, fold, parse, position, trap,
};
",
    );
    for property in properties {
        assert!(
            property.values.len() <= usize::from(u16::MAX),
            "{} has more values than a u16 counts",
            property.rust_type
        );
        if matches!(property.kind, Kind::Binary) {
            continue;
        }
        let upper = snake_name(property).to_uppercase();
        let ty = property.rust_type;
        writeln!(out, "\nconst {upper}: &[{ty}] = &[").unwrap();
        for value in &property.values {
            writeln!(out, "    {},", value.icu).unwrap();
        }
        out.push_str("];\n");
    }
    out.push_str("\nimpl wit::Guest for Component {\n");
    for property in properties {
        let snake = snake_name(property);
        let upper = snake.to_uppercase();
        let (ranges, contains) = match property.kind {
            Kind::Binary => {
                rust_binary(&mut out, property);
                continue;
            }
            Kind::Category => ("category_ranges", "category_contains"),
            Kind::Enumerated => ("enumerated_ranges", "enumerated_contains"),
        };
        write!(
            out,
            "    fn {snake}_ranges(value: u16) -> Vec<(u32, u32)> {{
        {ranges}(at({upper}, value))
    }}

    fn {snake}_contains(value: u16, ch: char) -> bool {{
        {contains}(at({upper}, value), ch)
    }}

    fn parse_{snake}(name: String, matching: wit::Matching) -> Option<u16> {{
        position({upper}, parse(&name, matching)?)
    }}

"
        )
        .unwrap();
    }
    out.truncate(out.len() - 1);
    out.push_str("}\n");
    out
}

/// A binary property has no value to look up: each one is a type of its own.
fn rust_binary(out: &mut String, property: &Property) {
    let arms = |call: &dyn Fn(&str) -> String| {
        let mut arms = String::new();
        for (index, value) in property.values.iter().enumerate() {
            writeln!(arms, "            {index} => {},", call(&value.icu)).unwrap();
        }
        arms.push_str("            _ => trap(),\n");
        arms
    };
    out.push_str(
        "    fn binary_property_ranges(value: u16) -> Vec<(u32, u32)> {\n        match value {\n",
    );
    out.push_str(&arms(&|p| format!("binary_ranges::<{p}>()")));
    out.push_str("        }\n    }\n\n");
    out.push_str(
        "    fn binary_property_contains(value: u16, ch: char) -> bool {\n        match value {\n",
    );
    out.push_str(&arms(&|p| format!("binary_contains::<{p}>(ch)")));
    out.push_str("        }\n    }\n\n");
    out.push_str(
        "    fn parse_binary_property(name: String, matching: wit::Matching) -> Option<u16> {\n        Some(match matching {\n            wit::Matching::Strict => match name.as_str() {\n",
    );
    for (index, value) in property.values.iter().enumerate() {
        writeln!(
            out,
            "                {} => {index},",
            quoted_alternatives(&value.strict_names)
        )
        .unwrap();
    }
    out.push_str("                _ => return None,\n            },\n            wit::Matching::Loose => match fold(&name).as_str() {\n");
    for (index, value) in property.values.iter().enumerate() {
        writeln!(
            out,
            "                {} => {index},",
            quoted_alternatives(&value.loose_names)
        )
        .unwrap();
    }
    out.push_str("                _ => return None,\n            },\n        })\n    }\n\n");
}

fn quoted_alternatives(names: &[String]) -> String {
    names
        .iter()
        .map(|n| format!("{n:?}"))
        .collect::<Vec<_>>()
        .join(" | ")
}

fn wado(properties: &[Property]) -> String {
    let mut out = String::new();
    out.push_str(
        "#![generated(by = \"icu-gen-properties\")]
#![stdlib(\"core:icu/properties.wado\")]

use { Properties } from \"../icu.wat\" with { type: \"wat\" };
use { CodePointSet, PropertyNameError, fold, refused } from \"core:icu/code_point_set.wado\";
",
    );
    for property in properties {
        let snake = snake_name(property);
        let ty = property.rust_type;
        let (doc, what) = match property.kind {
            Kind::Binary => (
                "The binary properties, each the set of code points that have it.".to_string(),
                "a binary property".to_string(),
            ),
            Kind::Category => (
                format!(
                    "The values of {} (`{}`): the categories, and the groups UAX #44 names\n/// over them (`Letter` is `L`).",
                    property.names[0], property.names[1]
                ),
                format!("a value of {}", property.names[0]),
            ),
            Kind::Enumerated => (
                format!(
                    "The values of {} (`{}`).",
                    property.names[0],
                    property.names[property.names.len() - 1]
                ),
                format!("a value of {}", property.names[0]),
            ),
        };
        writeln!(out, "\n/// {doc}\npub enum {ty} {{").unwrap();
        for value in &property.values {
            writeln!(out, "    {},", value.case).unwrap();
        }
        write!(
            out,
            "}}

impl CodePointSet for {ty} {{
    fn ranges(&self) -> List<[u32, u32]> {{
        return Properties::{snake}_ranges(ReflectEnum::<{ty}>::discriminant(self) as u16);
    }}

    fn contains(&self, ch: char) -> bool {{
        return Properties::{snake}_contains(ReflectEnum::<{ty}>::discriminant(self) as u16, ch);
    }}
}}
"
        )
        .unwrap();
        for (trait_name, method, matching) in [
            ("FromStr", "from_str", "Strict"),
            ("LenientFromStr", "from_str_lenient", "Loose"),
        ] {
            write!(
                out,
                "
impl {trait_name} for {ty} {{
    type Err = PropertyNameError;

    fn {method}<S: AsStrSlice>(s: S) -> Result<{ty}, PropertyNameError> {{
        let name = s.to_string();
        let Some(index) = Properties::parse_{snake}(name, {matching}) else {{
            return Err(refused(name, \"{what}\"));
        }};
        return Ok(ReflectEnum::<{ty}>::from_discriminant(index as i32).unwrap());
    }}
}}
"
            )
            .unwrap();
        }
    }

    out.push_str(
        "
/// A property, or a value of one, named at run time: what a `\\p{...}` in a
/// grammar names. It parses from a binary property's name (`White_Space`) or
/// from `property=value` (`sc=Latin`), as `FromStr` or `LenientFromStr` match
/// names.
pub variant Property {
",
    );
    for property in properties {
        let ty = property.rust_type;
        writeln!(out, "    {ty}({ty}),").unwrap();
    }
    out.push_str("}\n");

    out.push_str("\nimpl CodePointSet for Property {\n");
    for (method, params, args) in [("ranges", "", ""), ("contains", ", ch: char", "ch")] {
        let ret = if method == "ranges" {
            "List<[u32, u32]>"
        } else {
            "bool"
        };
        writeln!(
            out,
            "    fn {method}(&self{params}) -> {ret} {{\n        return match *self {{"
        )
        .unwrap();
        for property in properties {
            let ty = property.rust_type;
            writeln!(out, "            {ty}(p) => p.{method}({args}),").unwrap();
        }
        out.push_str("        };\n    }\n\n");
    }
    out.truncate(out.len() - 1);
    out.push_str("}\n");

    for (trait_name, method, strict) in [
        ("FromStr", "from_str", true),
        ("LenientFromStr", "from_str_lenient", false),
    ] {
        write!(
            out,
            "
impl {trait_name} for Property {{
    type Err = PropertyNameError;

    fn {method}<S: AsStrSlice>(s: S) -> Result<Property, PropertyNameError> {{
        let text = s.to_string();
        let Some([name, value]) = text.split_once(\"=\") else {{
            return Ok(Property::BinaryProperty(BinaryProperty::{method}(&text)?));
        }};
        return match {key} {{
",
            key = if strict { "name" } else { "fold(name)" },
        )
        .unwrap();
        for property in properties {
            if matches!(property.kind, Kind::Binary) {
                continue;
            }
            let ty = property.rust_type;
            let names: Vec<String> = if strict {
                property.names.clone()
            } else {
                property
                    .names
                    .iter()
                    .map(|n| fold(n))
                    .collect::<BTreeSet<_>>()
                    .into_iter()
                    .collect()
            };
            writeln!(
                out,
                "            {} => Ok(Property::{ty}({ty}::{method}(value)?)),",
                quoted_alternatives(&names)
            )
            .unwrap();
        }
        out.push_str(
            "            _ => Err(refused(text, \"a property=value pair\")),
        };
    }
}
",
        );
    }
    out
}

/// UAX #44 loose matching, as the component's own `fold` does it.
fn fold(name: &str) -> String {
    name.chars()
        .filter(|c| !matches!(c, '_' | '-' | ' '))
        .map(|c| c.to_ascii_lowercase())
        .collect()
}
