//! Writes the `properties` interface of `core:icu` from ICU4X's own names.
//!
//! Every property has exports of its own (`<p>-ranges`, `<p>-contains`,
//! `parse-<p>`). That is what lets the link-time collection keep only the data
//! of the properties a program names: one export per question would root them
//! all.
//!
//! A value crosses as its position among its property's values, and each side
//! holds the list: the facade as a Wado enum, the component as a table of
//! ICU4X values. A WIT enum would say the same, but a component carries its
//! types' case names in every program that links it, named or not.
//!
//! Usage: `icu-gen-properties <repository root>`. It writes
//!
//! - `wado-bundled-icu/wit-properties/properties.wit`, the interface;
//! - `wado-bundled-icu/src/properties/values.rs`, each position's ICU4X value
//!   and the exports' implementations;
//! - `wado-compiler/lib/core/icu/properties.wado`, the enums and their impls.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::Path;

use heck::{ToKebabCase, ToUpperCamelCase};
use icu_properties::PropertyNamesLong;
use icu_properties::props::{
    BidiClass, BinaryProperty, CanonicalCombiningClass, EastAsianWidth, EnumeratedProperty,
    GeneralCategory, GraphemeClusterBreak, HangulSyllableType, IndicConjunctBreak,
    IndicSyllabicCategory, JoiningGroup, JoiningType, LineBreak, NamedEnumeratedProperty,
    NumericType, Script, SentenceBreak, VerticalOrientation, WordBreak,
};

const HEADER: &str =
    "Generated by `mise run update-bundled-icu` from ICU4X's property names. Do not edit by hand.";

/// One property, as all three outputs need it.
struct Property {
    /// The ICU4X type, which the Wado enum is named after.
    rust_type: &'static str,
    /// The UCD names a `Property` parse matches the property by.
    names: Vec<String>,
    /// How the generated Rust reaches the data.
    kind: Kind,
    values: Vec<Value>,
}

enum Kind {
    Binary,
    Category,
    Enumerated,
}

struct Value {
    /// The Wado case.
    case: String,
    /// The Rust expression for the ICU4X value: a type for a binary property,
    /// a constant otherwise.
    icu: String,
    /// The names a binary property's parse accepts, folded. Empty for the
    /// other kinds, whose parse ICU4X's own name tables answer.
    loose_names: Vec<String>,
    /// Likewise, the exact spellings a strict parse accepts.
    strict_names: Vec<String>,
}

fn main() {
    let root = std::env::args()
        .nth(1)
        .expect("usage: icu-gen-properties <repository root>");
    let root = Path::new(&root);
    let properties = properties();
    write(
        &root.join("wado-bundled-icu/wit-properties/properties.wit"),
        &wit(&properties),
    );
    write(
        &root.join("wado-bundled-icu/src/properties/values.rs"),
        &rust(&properties),
    );
    write(
        &root.join("wado-compiler/lib/core/icu/properties.wado"),
        &wado(&properties),
    );
}

fn write(path: &Path, text: &str) {
    std::fs::write(path, text).unwrap_or_else(|e| panic!("cannot write {}: {e}", path.display()));
}

/// The enumerated property `$ty`, whose raw value is a `$raw`. Listing every
/// value takes the raw constructor, which ICU4X deprecates; the code written
/// names each value's constant instead.
macro_rules! enumerated {
    ($ty:ident, $raw:ty) => {
        #[allow(deprecated)]
        enumerated::<$ty>(stringify!($ty), 0..=<$raw>::MAX.into(), |v| {
            $ty::from_icu4c_value(<$raw>::try_from(v).unwrap())
        })
    };
}

fn properties() -> Vec<Property> {
    let out = vec![
        binary(),
        category(),
        enumerated!(BidiClass, u8),
        enumerated!(CanonicalCombiningClass, u8),
        enumerated!(EastAsianWidth, u8),
        enumerated!(GraphemeClusterBreak, u8),
        enumerated!(HangulSyllableType, u8),
        enumerated!(IndicConjunctBreak, u8),
        enumerated!(IndicSyllabicCategory, u8),
        enumerated!(JoiningGroup, u8),
        enumerated!(JoiningType, u8),
        enumerated!(LineBreak, u8),
        enumerated!(NumericType, u8),
        enumerated!(Script, u16),
        enumerated!(SentenceBreak, u8),
        enumerated!(VerticalOrientation, u8),
        enumerated!(WordBreak, u8),
    ];
    for property in &out {
        let mut seen = BTreeSet::new();
        for value in &property.values {
            assert!(
                seen.insert(&value.case),
                "{}: two values spell the case `{}`",
                property.rust_type,
                value.case
            );
        }
    }
    out
}

/// A property's long name, then its short one where that differs.
fn ucd_names(long: &[u8], short: &[u8]) -> Vec<String> {
    let utf8 = |bytes: &[u8]| String::from_utf8(bytes.to_vec()).expect("ICU4X names are ASCII");
    let mut names = vec![utf8(long)];
    if short != long {
        names.push(utf8(short));
    }
    names
}

/// Every value of `T` that has a long name, in ICU4X's order. ICU4X names the
/// constant of each after its long name, as it does General_Category's.
fn enumerated<T: NamedEnumeratedProperty + EnumeratedProperty>(
    rust_type: &'static str,
    raw: std::ops::RangeInclusive<u32>,
    from_raw: impl Fn(u32) -> T,
) -> Property {
    let long = PropertyNamesLong::<T>::new();
    let values = raw
        .filter_map(|v| {
            let name = long.get(from_raw(v))?;
            Some(Value {
                case: case_name(name),
                icu: format!("{rust_type}::{}", name.replace('_', "")),
                loose_names: Vec::new(),
                strict_names: Vec::new(),
            })
        })
        .collect();
    Property {
        rust_type,
        names: ucd_names(T::NAME, T::SHORT_NAME),
        kind: Kind::Enumerated,
        values,
    }
}

/// The 30 categories and the 8 groups UAX #44 names over them. ICU4X names the
/// constant of each after its long name.
fn category() -> Property {
    let long = PropertyNamesLong::<GeneralCategory>::new();
    let categories = (0..=u8::MAX)
        .filter_map(|v| GeneralCategory::try_from(v).ok())
        .map(|gc| {
            long.get(gc)
                .expect("every General_Category value has a long name")
                .to_string()
        });
    let groups = [
        "Cased_Letter",
        "Letter",
        "Mark",
        "Number",
        "Punctuation",
        "Symbol",
        "Separator",
        "Other",
    ]
    .map(String::from);
    let values = categories
        .chain(groups)
        .map(|name| Value {
            case: case_name(&name),
            icu: format!("GeneralCategoryGroup::{}", name.replace('_', "")),
            loose_names: Vec::new(),
            strict_names: Vec::new(),
        })
        .collect();
    Property {
        rust_type: "GeneralCategoryGroup",
        names: ucd_names(GeneralCategory::NAME, GeneralCategory::SHORT_NAME),
        kind: Kind::Category,
        values,
    }
}

/// The binary properties, each optionally with the aliases `PropertyAliases.txt`
/// gives it beyond the long and short names ICU4X knows. ICU4X has no name
/// table to parse these by, so the list is the table.
macro_rules! binary_properties {
    ($($ty:ident $(=> [$($alias:literal),+])?),+ $(,)?) => {
        fn binary() -> Property {
            let values = vec![$({
                let strict_names: Vec<String> = ucd_names(
                    <icu_properties::props::$ty as BinaryProperty>::NAME,
                    <icu_properties::props::$ty as BinaryProperty>::SHORT_NAME,
                )
                .into_iter()
                .chain([$($($alias.to_string()),+)?])
                .collect();
                let loose_names = strict_names.iter().map(|n| fold(n)).collect();
                Value {
                    case: stringify!($ty).to_string(),
                    icu: stringify!($ty).to_string(),
                    loose_names,
                    strict_names,
                }
            }),+];
            Property {
                rust_type: "BinaryProperty",
                names: Vec::new(),
                kind: Kind::Binary,
                values,
            }
        }
    };
}

