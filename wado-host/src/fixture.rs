//! What an e2e fixture's `__DATA__` section says about how to compile it, read
//! once for both the e2e harness and the golden dumps, so the goldens record
//! the program the tests run.

use std::collections::BTreeMap;

use indexmap::IndexMap;
use serde::de::Error as _;
use serde::{Deserialize, Deserializer};
use wado_compiler::OptLevel;
use wado_compiler::coverage::CoverageScope;
use wado_compiler::param_resolution::{ParamInputs, ParamPolicy, ParamPolicyLevel};

use crate::HostStubs;

/// The level a WIR golden records.
pub const GOLDEN_OPT_LEVEL: OptLevel = OptLevel::O2;

/// The text after a fixture's `__DATA__` line, if it has one.
#[must_use]
pub fn data_section(source: &str) -> Option<&str> {
    let marker = "\n__DATA__\n";
    match source.find(marker) {
        Some(pos) => Some(&source[pos + marker.len()..]),
        None => source.strip_prefix("__DATA__\n"),
    }
}

/// A level as `__DATA__` spells it (`only_opt`, `wir_expect:O2`).
#[must_use]
pub fn opt_level_name(level: OptLevel) -> &'static str {
    match level {
        OptLevel::O0 => "O0",
        OptLevel::O1 => "O1",
        OptLevel::O2 => "O2",
        OptLevel::O3 => "O3",
        OptLevel::Os => "Os",
    }
}

/// Whether a fixture is written to fail its compile: its `__DATA__` expects a
/// `compile_error` message, as the e2e harness reads it, or the module is
/// `#![TODO]`. A `__DATA__` that is not JSON expects none: the grammar corpus
/// reads sources that are no fixture.
#[must_use]
pub fn expects_compile_failure(source: &str) -> bool {
    let expects_error = data_section(source)
        .and_then(|data| serde_json::from_str::<serde_json::Value>(data.trim()).ok())
        .is_some_and(|spec| {
            spec.get("compile_error")
                .is_some_and(serde_json::Value::is_string)
        });
    if expects_error {
        return true;
    }
    for line in source.lines() {
        let t = line.trim();
        if t.is_empty() || t.starts_with("//") {
            continue;
        }
        if t.starts_with("#![") {
            if t.contains("TODO") {
                return true;
            }
            continue;
        }
        break;
    }
    false
}

/// The compile inputs a fixture's `__DATA__` section names; none without one.
///
/// # Errors
/// If the `__DATA__` section is not a JSON object of the fixture spec's shape.
pub fn compile_inputs(source: &str) -> Result<CompileInputs, String> {
    let Some(data) = data_section(source) else {
        return Ok(CompileInputs::default());
    };
    serde_json::from_str(data.trim()).map_err(|e| format!("__DATA__ is not a fixture spec: {e}"))
}

/// Whether the fixture has a WIR golden: the WIR its e2e run compiles at
/// [`GOLDEN_OPT_LEVEL`] under its first allocator.
#[must_use]
pub fn has_wir_golden(source: &str, inputs: &CompileInputs) -> bool {
    !expects_compile_failure(source) && inputs.compiles_at(GOLDEN_OPT_LEVEL)
}

/// The banner a golden dump opens with, naming the phase, the fixture, and how
/// to regenerate it.
#[must_use]
pub fn golden_header(title: &str, input_path: &str) -> String {
    format!(
        "// Golden file: {title}\n\
         // Source: {input_path}\n\
         // Generated by: mise run update-golden-fixtures\n\n"
    )
}

/// A WIR golden's whole text.
#[must_use]
pub fn wir_golden(input_path: &str, unparsed_wir: &str) -> String {
    let title = format!(
        "WIR with -{} optimization",
        opt_level_name(GOLDEN_OPT_LEVEL)
    );
    let mut text = golden_header(&title, input_path);
    text.push_str(unparsed_wir);
    text
}

/// The compile inputs among a fixture's `__DATA__` keys. The other keys state
/// expectations, which only the e2e harness reads.
#[derive(Debug, Default, Deserialize)]
pub struct CompileInputs {
    /// The `-f` codegen flags to compile with, at every level.
    #[serde(default)]
    pub codegen_flags: Vec<String>,
    /// Compile-time parameter overrides (`-D NAME=value`) for `#[param]` globals.
    #[serde(default)]
    pub params: IndexMap<String, String>,
    /// Stubbed compile-time environment for `#[param(from_env = ...)]`.
    #[serde(default)]
    pub param_env: IndexMap<String, String>,
    /// Host-supplied parameter fallbacks, as `wado test` supplies `log.level`.
    #[serde(default)]
    pub param_defaults: IndexMap<String, String>,
    /// Stubbed path `[dependencies]`: name → the dependency's `[package].lib`,
    /// relative to the fixture directory. Each entry is its own package.
    #[serde(default)]
    pub dependencies: IndexMap<String, String>,
    /// Stubbed package roots, each a directory relative to the fixture
    /// directory that stands where a `wado.toml` would. Empty leaves every
    /// module in no package.
    #[serde(default)]
    pub package_roots: Vec<String>,
    /// Stubbed path `[build-dependencies]`: nickname → the generator's `.wado`
    /// file, relative to the fixture directory.
    #[serde(default)]
    pub build_dependencies: IndexMap<String, String>,
    /// Stubbed remote files: URL → the file it serves, relative to the fixture
    /// directory.
    #[serde(default)]
    pub remote: IndexMap<String, String>,
    /// Override the `--param-unknown` policy level (`error` / `warn` / `ignore`).
    #[serde(default, deserialize_with = "policy_level")]
    pub param_unknown: Option<ParamPolicyLevel>,
    /// Override the `--param-invalid` policy level (`error` / `warn` / `ignore`).
    #[serde(default, deserialize_with = "policy_level")]
    pub param_invalid: Option<ParamPolicyLevel>,
    /// Override the `--param-missing` policy level (`error` / `warn` / `ignore`).
    #[serde(default, deserialize_with = "policy_level")]
    pub param_missing: Option<ParamPolicyLevel>,
    /// The allocators to run under, one run each: a name (`"debug"`,
    /// `"freelist"`) or a list of them.
    #[serde(default, deserialize_with = "one_or_many")]
    pub allocator: Vec<String>,
    /// Compile only at the listed optimization levels (e.g. `["O3"]`).
    #[serde(default)]
    pub only_opt: Vec<String>,
    /// Measure the fixture's own code under its `test` blocks, as
    /// `wado test --coverage` does, and state what they left unrun.
    #[serde(default)]
    pub coverage: Option<CoverageSpec>,
}

/// What a fixture's tests leave unrun in the fixture itself. Each list is the
/// whole set, so a region the plan gains or loses is a failure too.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct CoverageSpec {
    #[serde(default)]
    pub uncovered_lines: Vec<u32>,

    /// Each as `Branch::describe` spells it: `"12:5 else"`.
    #[serde(default)]
    pub uncovered_branches: Vec<String>,

    /// Qualified names, closures as `outer::{closure:LINE}`.
    #[serde(default)]
    pub uncovered_functions: Vec<String>,

    /// How often each countable line ran, over every test, as LCOV's `DA`
    /// lines carry it.
    pub line_counts: Option<BTreeMap<u32, i64>>,
}

/// A `__DATA__` value that is one string or a list of them.
fn one_or_many<'de, D: Deserializer<'de>>(de: D) -> Result<Vec<String>, D::Error> {
    #[derive(Deserialize)]
    #[serde(untagged)]
    enum OneOrMany {
        One(String),
        Many(Vec<String>),
    }
    match OneOrMany::deserialize(de)? {
        OneOrMany::One(one) => Ok(vec![one]),
        OneOrMany::Many(many) if many.is_empty() => {
            Err(D::Error::custom("an empty list names no allocator"))
        }
        OneOrMany::Many(many) => Ok(many),
    }
}

/// A level is rejected while `__DATA__` is read, so the reader that knows which
/// fixture it is reading reports it.
fn policy_level<'de, D: Deserializer<'de>>(de: D) -> Result<Option<ParamPolicyLevel>, D::Error> {
    let level = String::deserialize(de)?;
    ParamPolicyLevel::parse(&level)
        .map(Some)
        .ok_or_else(|| D::Error::custom(format!("invalid policy level: {level:?}")))
}

impl CompileInputs {
    /// What the compiling host answers from these inputs.
    #[must_use]
    pub fn host_stubs(&self) -> HostStubs {
        HostStubs {
            env: self.param_env.clone(),
            dependencies: self.dependencies.clone(),
            package_roots: self.package_roots.clone(),
            build_dependencies: self.build_dependencies.clone(),
            remote: self.remote.clone(),
        }
    }

    /// The `#[param]` inputs the compiler resolves against.
    #[must_use]
    pub fn param_inputs(&self) -> ParamInputs {
        let defaults = ParamPolicy::default();
        let policy = ParamPolicy {
            unknown: self.param_unknown.unwrap_or(defaults.unknown),
            invalid: self.param_invalid.unwrap_or(defaults.invalid),
            missing: self.param_missing.unwrap_or(defaults.missing),
        };
        ParamInputs {
            overrides: self.params.clone().into_iter().collect(),
            defaults: self.param_defaults.clone().into_iter().collect(),
            policy,
        }
    }

    /// The allocators the fixture runs under, in order. Unset runs `debug`,
    /// which catches a use-after-free.
    #[must_use]
    pub fn allocators(&self) -> Vec<&str> {
        if self.allocator.is_empty() {
            return vec!["debug"];
        }
        self.allocator.iter().map(String::as_str).collect()
    }

    /// Whether `only_opt` admits `level`.
    #[must_use]
    pub fn compiles_at(&self, level: OptLevel) -> bool {
        let name = opt_level_name(level);
        self.only_opt.is_empty() || self.only_opt.iter().any(|only| only == name)
    }

    /// The coverage the compile instruments for.
    #[must_use]
    pub fn coverage_scope(&self) -> Option<CoverageScope> {
        self.coverage.as_ref().map(|_| CoverageScope::default())
    }
}

#[cfg(test)]
mod tests {
    use super::expects_compile_failure;

    #[test]
    fn compile_error_is_read_as_the_harness_reads_it() {
        assert!(expects_compile_failure(
            "fn f() {}\n__DATA__\n{\"compile_error\": \"boom\"}\n"
        ));
        assert!(!expects_compile_failure(
            "fn f() {}\n__DATA__\n{\"compile_error\": null}\n"
        ));
        assert!(!expects_compile_failure(
            "fn f() {}\n__DATA__\n{\"stdout\": \"\\\"compile_error\\\"\"}\n"
        ));
        assert!(!expects_compile_failure(
            "fn f() {}\n__DATA__\nnot json \"compile_error\"\n"
        ));
    }
}
