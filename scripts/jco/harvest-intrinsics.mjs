// Extract the FutureEnd / FutureWritableEnd / FutureReadableEnd classes from a
// future-using component (future_trigger.wado) transpiled by released jco, so
// they stay version-matched. Re-run after a jco bump to refresh.
//
// Usage: node harvest-intrinsics.mjs <component.wasm> [out.js]

import { transpile } from "@bytecodealliance/jco";
import { readFile, writeFile } from "node:fs/promises";
import { basename } from "node:path";

const CLASSES = ["FutureEnd", "FutureWritableEnd", "FutureReadableEnd"];

// Extract a balanced `class Name { ... }` body (handles nested braces).
function extractClass(src, name) {
  const m = new RegExp(`class ${name}(?:\\s+extends\\s+\\w+)?\\s*\\{`).exec(src);
  if (!m) return null;
  let depth = 0;
  for (let j = src.indexOf("{", m.index); j < src.length; j++) {
    if (src[j] === "{") depth++;
    else if (src[j] === "}" && --depth === 0) return src.slice(m.index, j + 1);
  }
  return null;
}

const wasmPath = process.argv[2];
const outPath = process.argv[3] ?? new URL("./missing-intrinsics.js", import.meta.url).pathname;
if (!wasmPath) {
  console.error("Usage: node harvest-intrinsics.mjs <component.wasm> [out.js]");
  process.exit(1);
}

const name = basename(wasmPath).replace(/\.wasm$/, "");
const { files } = await transpile(await readFile(wasmPath), { name });
const src = new TextDecoder().decode(files[`${name}.js`]);

const blocks = CLASSES.map((c) => {
  const body = extractClass(src, c);
  if (!body) {
    console.error(`error: ${c} not found in transpiled output.`);
    console.error("The trigger component must exercise future.new (e.g. future_trigger.wado).");
    process.exit(1);
  }
  console.error(`  ${c}: ${body.split("\n").length} lines`);
  return body;
});

const header =
  "// GENERATED by scripts/jco/harvest-intrinsics.mjs — do not edit by hand.\n" +
  "// Future-end runtime classes harvested from released jco; injected by\n" +
  "// scripts/jco/postprocess.mjs. Regenerate after a jco bump.\n\n";

await writeFile(outPath, header + blocks.join("\n\n") + "\n");
console.error(`harvested ${CLASSES.length} classes → ${outPath}`);
